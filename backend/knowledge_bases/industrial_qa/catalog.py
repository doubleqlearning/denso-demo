DIRECTORY = Path(__file__).parent
TYPES_FILE = DIRECTORY / "catalog_types.yaml"
ASSETS_FILE = DIRECTORY / "catalog_assets.yaml"
PUBLIC_DIR = PROJECT_ROOT / "benchmark" / "public"

LOCATION_KEYS = ("site", "line_id", "station")
# Keys an asset ID or a model name may be written under.
NAME_KEYS = ("machine_id", "machine_model", "machine_model_specific", "component_id", "component_model")
_LINE_RE = re.compile(r"\bline\s*[-#]?\s*0*(\d+)\b", re.I)
_STATION_RE = re.compile(r"\bstation\s*[-#]?\s*0*(\d+)\b", re.I)
# Model-like names worth curating, for the build report.
_MODEL_TOKEN_RE = re.compile(
    r"\b(?:FX5[A-Z]*(?:-[0-9A-Z]+)*|MR-[A-Z0-9]+(?:-[A-Z0-9]+)*|HG-[A-Z]+\d*|i4L(?:-[0-9A-Z]+)?)\b"
)


def _fold(value: str) -> str:
    return re.sub(r"[\s\-_.]+", "", value.casefold())


def _spelling_re(spelling: str, suffix: str = "") -> re.Pattern[str]:
    words = [re.escape(word) for word in re.split(r"[\s\-]+", spelling.strip()) if word]
    return re.compile(r"(?<![\w-])" + r"[\s\-]?".join(words) + suffix + r"(?![\w-])", re.I)


# Order codes extend a component model: FX5U-32MT is an FX5U, HG-KN13 an HG-KN.
_ORDER_CODE = r"(?:-?\d+[A-Z]*)?"


@dataclass(frozen=True)
class Family:
    """An equipment family: the canonical machine_model of its assets."""

    name: str
    kind: str
    manual: str
    id_prefix: str
    aliases: tuple[str, ...] = ()

    @property
    def id_pattern(self) -> re.Pattern[str]:
        words = [re.escape(word) for word in re.split(r"[\s\-]+", self.id_prefix) if word]
        return re.compile(
            r"(?<![\w-])" + r"[\s\-]?".join(words) + r"[\s\-]?(\d+)(?![\w-])", re.I
        )


@dataclass(frozen=True)
class Component:
    name: str
    family: str
    kind: str
    aliases: tuple[str, ...] = ()


@dataclass(frozen=True)
class Asset:
    """A plant asset and where the conversation introducing it locates it."""

    machine_id: str
    machine_model: str
    site: str | None = None
    line_id: str | None = None
    station: str | None = None

    def scope(self) -> dict[str, str]:
        values = {
            "machine_model": self.machine_model,
            "site": self.site,
            "line_id": self.line_id,
            "station": self.station,
        }
        return {key: value for key, value in values.items() if value}


class Catalog:
    """Canonical names of families, components, sites, lines, stations and assets."""

    def __init__(
        self,
        families: Sequence[Family],
        components: Sequence[Component] = (),
        sites: Mapping[str, Sequence[str]] | None = None,
        processes: Sequence[str] = (),
        assets: Mapping[str, Asset] | None = None,
        lines: Sequence[str] = (),
        stations: Sequence[str] = (),
        *,
        source: str = "",
    ) -> None:
        self.families = {family.name: family for family in families}
        self.components = {component.name: component for component in components}
        self.sites = {site: tuple(aliases) for site, aliases in (sites or {}).items()}
        self.processes = {process.casefold(): process for process in processes}
        self.assets = dict(assets or {})
        self.lines = tuple(lines)
        self.stations = tuple(stations)
        self.source = source
        self._family_index = self._index(
            (family.name, (family.name, *family.aliases)) for family in families
        )
        self._component_index = self._index(
            (component.name, (component.name, *component.aliases)) for component in components
        )
        # Longest spelling first, so "Plant Hanoi" wins over "Hanoi".
        self._site_spellings = sorted(
            ((_spelling_re(spelling), site, len(spelling))
             for site, aliases in self.sites.items() for spelling in (site, *aliases)),
            key=lambda item: -item[2],
        )
        self._component_spellings = sorted(
            ((_spelling_re(spelling, _ORDER_CODE), name, len(spelling))
             for name, component in self.components.items()
             for spelling in (name, *component.aliases)),
            key=lambda item: -item[2],
        )
        process = "|".join(map(re.escape, self.processes.values())) or "(?!)"
        # "Palletizing cell D", "cell D palletizing" or a bare "cell D".
        self._cell_re = re.compile(
            rf"\b(?:({process})\s+)?cell\s*[-#]?\s*([A-Z])\b(?:\s+({process})\b)?", re.I
        )

    @staticmethod
    def _index(entries: Iterable[tuple[str, Iterable[str]]]) -> dict[str, str]:
        index: dict[str, str] = {}
        for name, spellings in entries:
            for spelling in spellings:
                if index.setdefault(_fold(spelling), name) != name:
                    raise ValueError(f"{spelling!r} names both {index[_fold(spelling)]!r} and {name!r}")
        return index

    # ------------------------------------------------------------------ files

    @classmethod
    def from_files(cls, types: Path = TYPES_FILE, assets: Path | None = ASSETS_FILE) -> "Catalog":
        """The curated types plus, when the file exists, the generated assets."""

        type_source = types.read_text(encoding="utf-8")
        data = yaml.safe_load(type_source) or {}
        families = [
            Family(
                name=str(name),
                kind=str(spec.get("kind") or ""),
                manual=str(spec.get("manual") or ""),
                id_prefix=str(spec["id_prefix"]),
                aliases=tuple(map(str, spec.get("aliases") or ())),
            )
            for name, spec in (data.get("families") or {}).items()
        ]
        components = [
            Component(
                name=str(name),
                family=str(spec["family"]),
                kind=str(spec.get("kind") or ""),
                aliases=tuple(map(str, spec.get("aliases") or ())),
            )
            for name, spec in (data.get("components") or {}).items()
        ]
        sites = {str(site): tuple(map(str, aliases or ())) for site, aliases in (data.get("sites") or {}).items()}
        processes = [str(process) for process in data.get("processes") or ()]

        asset_source = ""
        generated: dict[str, Any] = {}
        if assets is not None and assets.is_file():
            asset_source = assets.read_text(encoding="utf-8")
            generated = yaml.safe_load(asset_source) or {}
        return cls(
            families,
            components,
            sites,
            processes,
            assets={
                str(machine_id): Asset(
                    machine_id=str(machine_id),
                    machine_model=str(spec["machine_model"]),
                    site=spec.get("site"),
                    line_id=spec.get("line_id"),
                    station=spec.get("station"),
                )
                for machine_id, spec in (generated.get("assets") or {}).items()
            },
            lines=[str(line) for line in generated.get("lines") or ()],
            stations=[str(station) for station in generated.get("stations") or ()],
            source=type_source + "\n---\n" + asset_source,
        )

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self.source.encode("utf-8")).hexdigest()

    # -------------------------------------------------------------- parsing

    def asset_ids(self, text: str) -> list[str]:
        """Canonical asset IDs named in `text`, in order of first mention."""

        found: list[tuple[int, str]] = []
        for family in self.families.values():
            for match in family.id_pattern.finditer(text):
                found.append((match.start(), f"{family.id_prefix}{match.group(1)}"))
        return list(dict.fromkeys(asset_id for _, asset_id in sorted(found)))

    def without_asset_ids(self, text: str) -> str:
        for family in self.families.values():
            text = family.id_pattern.sub(" ", text)
        return re.sub(r"\s+", " ", text).strip(" ,;:/-()")

    def family_of(self, asset_id: str) -> str | None:
        return next(
            (family.name for family in self.families.values()
             if family.id_pattern.fullmatch(asset_id)),
            None,
        )

    def family(self, value: str) -> str | None:
        """Family named by `value`, also when a generic word follows ("FX5 CPU unit")."""

        folded = _fold(value)
        if folded in self._family_index:
            return self._family_index[folded]
        words = re.split(r"[\s,;/()]+", value.strip())
        for size in range(len(words) - 1, 0, -1):
            if (name := self._family_index.get(_fold(" ".join(words[:size])))) is not None:
                return name
        return None

    def component(self, value: str) -> str | None:
        """Component model named in `value` ("FX5-ENET module" -> FX5-ENET)."""

        if (name := self._component_index.get(_fold(value))) is not None:
            return name
        return next(
            (name for pattern, name, _ in self._component_spellings if pattern.search(value)),
            None,
        )

    def machine_variant(self, value: str) -> tuple[str, str] | None:
        """(family, specific model) for a manufacturer suffix, never an asset ID."""
        for family in self.families.values():
            match = _spelling_re(family.name, suffix=r"-[A-Z0-9][A-Z0-9./_-]*").search(value)
            if not match:
                continue
            model = match.group(0)
            if not (self.asset_ids(model) or self.family(model) or self.component(model)):
                return family.name, model
        return None

    def lookup_scope(self, assets: Sequence[str], family: str | None = None) -> dict[str, Any] | None:
        """Known asset IDs outrank family metadata; other assets never join the fallback."""
        def any_of(conditions):
            return conditions[0] if len(conditions) == 1 else {"$or": conditions}

        assets = list(dict.fromkeys(assets))
        if assets and all(asset in self.assets for asset in assets):
            exact = any_of([{"context.machine_id": {"$eq": asset}} for asset in assets])
            # Derive compatible families from the trusted catalog, even when
            # the caller or an old record carries an inconsistent family.
            families = sorted({self.assets[asset].machine_model for asset in assets})
            compatible = any_of([build_knowledge_filter(context={"machine_model": model}) for model in families])
            general = {"$and": [{"context.machine_id": {"$exists": False}}, compatible]}
            return {"$or": [exact, general]}
        scope = build_knowledge_filter(context={"machine_model": family})
        if assets:
            matches = any_of([build_knowledge_filter(context={"machine_id": asset}) for asset in assets])
            scope = {"$and": [matches, scope]} if scope else matches
        return scope

    def knowledge_filter(
        self, *, subject=None, knowledge_type=None, context=None, exact_context_keys=(), valid_on: date | None = None
    ) -> dict[str, Any] | None:
        """Shared industrial QA policy for benchmark and online agent retrieval."""
        values = dict(context or {})
        asset_value = str(values.pop("machine_id", None) or "").strip()
        model_value = str(values.pop("machine_model", None) or "").strip()
        assets = self.asset_ids(asset_value) or ([asset_value] if asset_value else [])
        family = self.family(model_value) if model_value else None
        if model_value and family is None:
            variant = self.machine_variant(model_value)
            component = self.component(model_value)
            family = variant[0] if variant else self.components[component].family if component else model_value
        scope = self.lookup_scope(assets, family)
        other = build_knowledge_filter(
            subject=subject, knowledge_type=knowledge_type, context=values,
            exact_context_keys=exact_context_keys, valid_on=valid_on,
        )
        return {"$and": [scope, other]} if scope and other else scope or other

    def site(self, value: str) -> str | None:
        return next(
            (site for pattern, site, _ in self._site_spellings if pattern.search(value)), None
        )

    def line(self, value: str) -> tuple[str | None, str | None]:
        """(site, "Line N") of a line written as "Dong Nai Line 1", "LINE11"..."""

        match = _LINE_RE.search(value)
        return self.site(value), f"Line {int(match.group(1))}" if match else None

    def site_lines(self, text: str) -> set[tuple[str, str]]:
        """(site, "Line N") pairs written together, as in "Dong Nai Line 1"."""

        pairs = set()
        for pattern, site, _ in self._site_spellings:
            for match in pattern.finditer(text):
                if line := re.match(r"\s+line\s*0*(\d+)\b", text[match.end():], re.I):
                    pairs.add((site, f"Line {int(line.group(1))}"))
        return pairs

    def station(self, value: str) -> str | None:
        """"<Process> cell X", a bare "cell X" or "Station N"."""

        if match := self._cell_re.search(value):
            letter = match.group(2).upper()
            process = match.group(1) or match.group(3)
            return f"{self.processes[process.casefold()]} cell {letter}" if process else f"cell {letter}"
        if match := _STATION_RE.search(value):
            return f"Station {int(match.group(1))}"
        return None

    def locate(self, texts: Sequence[str], asset_id: str) -> Asset:
        """The asset as introduced by the first text naming it.

        Only that turn counts: later turns mention other lines in passing
        ("back in 2019 on Hanoi Line 2").
        """

        intro = next((text for text in texts if asset_id in self.asset_ids(text)), "")
        site, line = self.line(intro)
        if line and not site:
            # "at Hai Phong Line 7" later in the conversation names the site.
            sites = {
                site for text in texts for site, named_line in self.site_lines(text)
                if named_line == line
            }
            site = sites.pop() if len(sites) == 1 else None
        return Asset(
            machine_id=asset_id,
            machine_model=self.family_of(asset_id) or "",
            site=site,
            line_id=line,
            station=self.station(intro),
        )

    # -------------------------------------------------------------- building

    def build(self, conversations: Iterable[Mapping[str, Any]]) -> dict[str, Any]:
        """catalog_assets.yaml content: assets, lines and stations of the conversations."""

        assets: dict[str, Asset] = {}
        lines: set[str] = set()
        stations: set[str] = set()
        for conversation in conversations:
            texts = [turn["text"] for turn in conversation["turns"]]
            for text in texts:
                lines.update(f"Line {int(m.group(1))}" for m in _LINE_RE.finditer(text))
                stations.update(
                    self.station(m.group(0)) or "" for m in self._cell_re.finditer(text)
                    if m.group(1) or m.group(3)
                )
                stations.update(f"Station {int(m.group(1))}" for m in _STATION_RE.finditer(text))
            for asset_id in self.asset_ids("\n".join(texts)):
                # The first conversation introducing an asset locates it.
                if asset_id not in assets:
                    assets[asset_id] = self.locate(texts, asset_id)
        stations.discard("")
        stations.update(asset.station for asset in assets.values() if asset.station)
        lines.update(asset.line_id for asset in assets.values() if asset.line_id)
        return {
            "lines": sorted(lines, key=lambda line: int(line.split()[-1])),
            "stations": sorted(stations),
            "assets": {
                asset_id: {
                    key: value
                    for key, value in (
                        ("machine_model", asset.machine_model),
                        ("site", asset.site),
                        ("line_id", asset.line_id),
                        ("station", asset.station),
                    )
                    if value
                }
                for asset_id, asset in sorted(assets.items())
            },
        }

    def uncovered_models(self, texts: Iterable[str]) -> Counter[str]:
        """Model-like names no family, component or asset ID covers."""

        missing: Counter[str] = Counter()
        for text in texts:
            for token in set(_MODEL_TOKEN_RE.findall(text)):
                if not (self.asset_ids(token) or self.family(token) or self.component(token)):
                    missing[token] += 1
        return missing

    # -------------------------------------------------------------- ontology

    def ontology_keys(self) -> dict[str, Any]:
        """Ontology keys (see backend.src.services.ontology) of the catalog."""

        def entry(aliases: Iterable[str] = (), description: str = "", implies=None):
            details = {
                "aliases": list(aliases) or None,
                "description": description or None,
                "implies": implies or None,
            }
            return {key: value for key, value in details.items() if value} or None

        return {
            "machine_id": {
                "description": "Plant asset ID",
                "values": {
                    asset_id: entry(implies=asset.scope())
                    for asset_id, asset in self.assets.items()
                },
            },
            "machine_model": {
                "values": {
                    family.name: entry(family.aliases, family.kind)
                    for family in self.families.values()
                },
            },
            "component_model": {
                "values": {
                    component.name: entry(
                        component.aliases, component.kind, {"machine_model": component.family}
                    )
                    for component in self.components.values()
                },
            },
            "site": {"values": {site: entry(aliases) for site, aliases in self.sites.items()}},
            "line_id": {"values": dict.fromkeys(self.lines)},
            "station": {"values": dict.fromkeys(self.stations)},
        }

    def ontology(self, base: Path | None = None) -> Ontology:
        """`base` ontology file (e.g. failure modes) extended with the catalog keys."""

        data = yaml.safe_load(base.read_text(encoding="utf-8")) if base and base.is_file() else {}
        data = dict(data or {})
        data["keys"] = {**(data.get("keys") or {}), **self.ontology_keys()}
        return Ontology.from_dict(
            data, source=yaml.safe_dump(data, sort_keys=False, allow_unicode=True)
        )

    # ---------------------------------------------------------- normalizing

    def normalize_records(self, transcript: str, records: Sequence[KnowledgeRecord]) -> None:
        """Canonical scope for the records extracted from one transcript.

        Rewrites names to the catalog, fills a missing machine_id from the
        cases a lesson cites or from the one asset the conversation names, and
        fills the location of a record's asset. A lesson without any location
        is general practice and stays unscoped unless its claim names an
        asset. Changes are recorded in revision["catalog"] as
        {"changed": {key: value before}, "inherited": "claim" | "case" |
        "conversation"}.
        """

        texts = transcript.splitlines()
        named = {
            asset_id: self.assets.get(asset_id) or self.locate(texts, asset_id)
            for asset_id in self.asset_ids(transcript)
        }
        keys = (*NAME_KEYS, *LOCATION_KEYS)
        before = {record.id: {key: record.context.get(key) for key in keys} for record in records}
        for record in records:
            self._canonical(record.context, named)

        by_id = {record.id: record for record in records}
        inherited: dict[Any, str] = {}
        # Cases first: a lesson inherits the asset of the cases it cites.
        for record in sorted(records, key=lambda record: record.type is not KnowledgeType.CASE):
            if not record.context.get("machine_id"):
                if found := self._incident_asset(record, by_id, named):
                    record.context["machine_id"], inherited[record.id] = found
            machine_id = record.context.get("machine_id")
            asset = named.get(machine_id) or self.assets.get(machine_id)
            if asset is not None:
                # Asset identity is authoritative for family. A specific model
                # is carried separately and cannot block the family lookup.
                record.context["machine_model"] = asset.machine_model
                for key, value in asset.scope().items():
                    if not record.context.get(key):
                        record.context[key] = value

        for record in records:
            note: dict[str, Any] = {
                key: old for key, old in before[record.id].items()
                if record.context.get(key) != old
            }
            if not note:
                continue
            report: dict[str, Any] = {"changed": note}
            if record.id in inherited:
                report["inherited"] = inherited[record.id]
            record.revision = {**record.revision, "catalog": report}

    def _incident_asset(
        self,
        record: KnowledgeRecord,
        by_id: Mapping[Any, KnowledgeRecord],
        named: Mapping[str, Asset],
    ) -> tuple[str, str] | None:
        if record.type is not KnowledgeType.CASE and not any(
            record.context.get(key) for key in LOCATION_KEYS
        ):
            # Unlocated: general practice, unless the claim names one asset.
            claimed = self.asset_ids(record.claim)
            return (claimed[0], "claim") if len(claimed) == 1 else None
        cited = {
            machine_id for ref in record.supported_by
            if ref in by_id and (machine_id := by_id[ref].context.get("machine_id"))
        }
        if len(cited) == 1:
            machine_id = cited.pop()
            asset = named.get(machine_id) or self.assets.get(machine_id)
            if asset is None or self._consistent(record.context, asset):
                return machine_id, "case"
        candidates = [
            asset_id for asset_id, asset in named.items()
            if self._consistent(record.context, asset)
        ]
        return (candidates[0], "conversation") if len(candidates) == 1 else None

    @staticmethod
    def _consistent(context: Mapping[str, Any], asset: Asset) -> bool:
        for key in LOCATION_KEYS:
            stated, located = context.get(key), getattr(asset, key)
            if stated and located and stated != located and not (
                key == "station" and str(located).endswith(f" {stated}")
            ):
                return False
        return True

    def _canonical(self, context: dict[str, Any], named: Mapping[str, Asset]) -> None:
        def text(key: str) -> str | None:
            value = context.get(key)
            return value.strip() if isinstance(value, str) and value.strip() else None

        # Asset IDs under any name key belong in machine_id.
        ids: list[str] = []
        for key in NAME_KEYS:
            if (value := text(key)) is None or not (found := self.asset_ids(value)):
                continue
            ids += found
            rest = self.without_asset_ids(value)
            if key == "machine_id":
                del context[key]
            elif key == "machine_model":
                context[key] = self.family_of(found[0])
            elif rest:
                context[key] = rest
            else:
                del context[key]
        if ids:
            context["machine_id"] = ids[0]

        if (value := text("machine_model")) is not None:
            if family := self.family(value):
                context["machine_model"] = family
            elif component := self.component(value):
                context.setdefault("component_model", component)
                context["machine_model"] = self.components[component].family
            elif variant := self.machine_variant(value):
                context.setdefault("machine_model_specific", variant[1])
                context["machine_model"] = variant[0]
        if not context.get("machine_model") and (value := text("machine_model_specific")):
            if variant := self.machine_variant(value):
                context["machine_model"] = variant[0]
        if (value := text("component_model")) is not None:
            if component := self.component(value):
                context["component_model"] = component
            elif family := self.family(value):
                context.setdefault("machine_model", family)
                del context["component_model"]

        # Locations, possibly written together ("Line 3, Palletizing cell D").
        for key in LOCATION_KEYS:
            if (value := text(key)) is None:
                continue
            site, line = self.line(value)
            parsed = {"site": site, "line_id": line, "station": self.station(value)}
            if parsed[key]:
                context[key] = parsed[key]
            elif any(parsed.values()):
                del context[key]  # another location written under this key
            # Otherwise an unknown spelling, kept for the ontology report.
            for other, found in parsed.items():
                if found and other != key and not text(other):
                    context[other] = found

        # A bare "cell C" is the cell of the conversation's asset there.
        if (station := text("station")) and station.startswith("cell "):
            matches = {
                asset.station for asset in named.values()
                if asset.station and asset.station.endswith(f" {station}")
            }
            if len(matches) == 1:
                context["station"] = matches.pop()


def load() -> Catalog:
    return Catalog.from_files()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("command", choices=("build",))
    parser.add_argument("--conversations", type=Path, default=PUBLIC_DIR / "conversations.jsonl")
    parser.add_argument("--chunks", type=Path, default=PUBLIC_DIR / "corpus_chunks.jsonl")
    parser.add_argument("--out", type=Path, default=ASSETS_FILE)
    args = parser.parse_args()

    catalog = Catalog.from_files(assets=None)
    raw = args.conversations.read_bytes()
    conversations = [json.loads(line) for line in raw.decode("utf-8").splitlines() if line.strip()]
    built = catalog.build(conversations)
    try:
        source = args.conversations.resolve().relative_to(PROJECT_ROOT)
    except ValueError:
        source = args.conversations
    header = (
        "# Generated by `python -m backend.knowledge_bases.industrial_qa.catalog build`\n"
        f"# from {source} (sha256 {hashlib.sha256(raw).hexdigest()[:16]});\n"
        "# do not edit: curate catalog_types.yaml and rebuild.\n"
    )
    args.out.write_text(
        header
        + yaml.safe_dump({key: built[key] for key in ("lines", "stations")}, sort_keys=False)
        + yaml.safe_dump(
            {"assets": built["assets"]}, sort_keys=False, allow_unicode=True,
            width=200, default_flow_style=None,
        ),
        encoding="utf-8",
    )
    assets = built["assets"].values()
    print(
        f"Wrote {args.out}: {len(built['assets'])} assets "
        f"({sum('line_id' in a for a in assets)} with a line, "
        f"{sum('station' in a for a in assets)} with a station, "
        f"{sum('site' in a for a in assets)} with a site), "
        f"{len(built['lines'])} lines, {len(built['stations'])} stations"
    )
    texts = [turn["text"] for c in conversations for turn in c["turns"]]
    if args.chunks.is_file():
        texts += [json.loads(line)["text"] for line in args.chunks.open(encoding="utf-8") if line.strip()]
    if missing := catalog.uncovered_models(texts):
        print("Model names not in catalog_types.yaml:", ", ".join(
            f"{name} ({count})" for name, count in missing.most_common(30)
        ))
    # The generated catalog must load as an ontology.
    Catalog.from_files(assets=args.out).ontology(DIRECTORY / "ontology.yaml")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
